/** Wie viele Einträge am Anfang der Liste Legacys Kern sind (`AVESMAPS_PLACE_KIND_LEGACY_PREFIX_LENGTH`). */
export const BAUWERK_ARTEN_KERN = 24;

/** Die fertige Artenliste: die lebenden Unterkategorien, dann Legacys Liste, soweit sie fehlt, ohne die linearen Anlagen (Reihenfolge tragend, siehe oben). */
export function schliesseArtenAb(online: readonly string[]): string[] {
    const arten = [...online];
    for (const legacy of BAUWERK_ARTEN_LEGACY) if (!arten.includes(legacy)) arten.push(legacy);
    return arten.filter((art) => !istAusgeschlossenerBauwerkTyp(art, BAUWERK_AUSGESCHLOSSEN));
}
